"""Generate the manuscript contribution statement from confirmed CRediT assignments."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "project/contributors.json"
OUTPUT = ROOT / "paper/setup/contributions.tex"
# Official role names: https://credit.niso.org/ (ANSI/NISO Z39.104-2022).
ROLES = (
    "Conceptualization", "Data curation", "Formal analysis", "Funding acquisition",
    "Investigation", "Methodology", "Project administration", "Resources", "Software",
    "Supervision", "Validation", "Visualization", "Writing – original draft",
    "Writing – review & editing",
)
HEADER = """% SPDX-FileCopyrightText: 2026 Schmiedmayer Lab and the project authors (see CONTRIBUTORS.md)
% SPDX-License-Identifier: MIT
% Generated by make contributions from project/contributors.json. Do not edit.

"""


def tex_escape(text: str) -> str:
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
                    "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
                    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "–": "--"}
    return "".join(replacements.get(char, char) for char in text)


def generate(data: dict, submission: bool = False) -> str:
    if not isinstance(data, dict) or set(data) != {"schema_version", "authors"} or data["schema_version"] != 1:
        raise ValueError("Expected schema_version 1 and an authors list")
    authors = data["authors"]
    if not isinstance(authors, list):
        raise ValueError("authors must be a list")
    if submission and not authors:
        raise ValueError("Assign and confirm author contributions before submission")
    names: set[str] = set()
    lines = []
    for author in authors:
        if not isinstance(author, dict) or set(author) != {"name", "roles", "confirmed"}:
            raise ValueError("Each author requires exactly name, roles, and confirmed")
        name, roles, confirmed = author["name"], author["roles"], author["confirmed"]
        if not isinstance(name, str) or not name.strip() or any(ord(c) < 32 for c in name):
            raise ValueError("Author names must be nonempty single-line text")
        if name != name.strip() or name.casefold() in names:
            raise ValueError(f"Duplicate or whitespace-padded author name: {name!r}")
        names.add(name.casefold())
        if not isinstance(roles, list) or not roles or any(role not in ROLES for role in roles):
            raise ValueError(f"{name}: roles must be a nonempty list of official CRediT names; use --roles")
        if len(set(roles)) != len(roles):
            raise ValueError(f"{name}: duplicate role")
        if not isinstance(confirmed, bool):
            raise ValueError(f"{name}: confirmed must be true or false")
        if submission and not confirmed:
            raise ValueError(f"{name}: contribution assignments have not been confirmed")
        assigned = "; ".join(tex_escape(role) for role in ROLES if role in roles)
        lines.append(r"\textbf{" + tex_escape(name) + "}: " + assigned + ".")
        if not confirmed:
            lines.append(r"\placeholder{Confirm the contribution assignments for " + tex_escape(name) + ".}")
    if not authors:
        lines = [r"\placeholder{Assign CRediT roles in project/contributors.json and obtain author confirmation.}"]
    return HEADER + "\\newcommand{\\papercontributions}{%\n" + "\n\\par\n".join(lines) + "\n}\n"


def check(submission: bool = False) -> None:
    expected = generate(json.loads(SOURCE.read_text(encoding="utf-8")), submission)
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
        raise ValueError("Contribution statement is stale; run make contributions")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--submission", action="store_true")
    parser.add_argument("--roles", action="store_true", help="List accepted role names")
    args = parser.parse_args()
    try:
        if args.roles:
            print("\n".join(ROLES))
        elif args.check:
            check(args.submission)
            print("OK: CRediT contribution statement is synchronized")
        else:
            OUTPUT.write_text(generate(json.loads(SOURCE.read_text(encoding="utf-8")), args.submission), encoding="utf-8")
            print("Wrote paper/setup/contributions.tex")
    except (ValueError, OSError) as error:
        parser.exit(1, f"ERROR: {error}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
